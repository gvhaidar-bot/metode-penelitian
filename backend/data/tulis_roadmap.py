def main():
    with io.open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    for job in data:
        if job["id"] in ROADMAP:
            job["roadmap"] = ROADMAP[job["id"]]
    with io.open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("roadmap ditulis untuk", len(ROADMAP), "karier")

if __name__ == "__main__":
    main()
